#pragma once

// System headers

namespace ReactorAsterix {

template <typename T>
T readBigEndian(const void* src) {
    T val;
    std::memcpy(&val, src, sizeof(T));
    if constexpr (sizeof(T) == 2) return ntohs(val);
    if constexpr (sizeof(T) == 4) return ntohl(val);
    return val;
}

}


